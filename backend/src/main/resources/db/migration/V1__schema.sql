-- Schéma initial Tunexa (compatible PostgreSQL ; montants en millimes : 1 TND = 1000)

CREATE TABLE governorates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(10)  NOT NULL UNIQUE,
    name_fr    VARCHAR(80)  NOT NULL,
    name_ar    VARCHAR(80)  NOT NULL,
    name_en    VARCHAR(80)  NOT NULL,
    shipping_zone INT       NOT NULL
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone         VARCHAR(20)  NOT NULL UNIQUE,
    email         VARCHAR(160) UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(80)  NOT NULL,
    last_name     VARCHAR(80)  NOT NULL,
    language      VARCHAR(2)   NOT NULL DEFAULT 'fr',
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    terms_accepted_at TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE otp_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target     VARCHAR(60)  NOT NULL,
    purpose    VARCHAR(30)  NOT NULL,
    code_hash  VARCHAR(100) NOT NULL,
    attempts   INT          NOT NULL DEFAULT 0,
    consumed   BOOLEAN      NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_otp_target ON otp_codes (target, purpose, created_at);

CREATE TABLE addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id),
    label          VARCHAR(40)  NOT NULL,
    full_name      VARCHAR(120) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    governorate_id BIGINT       NOT NULL REFERENCES governorates (id),
    delegation     VARCHAR(80)  NOT NULL,
    locality       VARCHAR(80),
    postal_code    VARCHAR(4)   NOT NULL,
    street         VARCHAR(200) NOT NULL,
    landmark       VARCHAR(200),
    is_default     BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_addresses_user ON addresses (user_id);

CREATE TABLE sellers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    shop_name        VARCHAR(120) NOT NULL UNIQUE,
    legal_name       VARCHAR(160) NOT NULL,
    tax_id           VARCHAR(20)  NOT NULL UNIQUE,
    rne_number       VARCHAR(30)  NOT NULL,
    rib              VARCHAR(20)  NOT NULL,
    pickup_address   VARCHAR(250) NOT NULL,
    governorate_id   BIGINT       NOT NULL REFERENCES governorates (id),
    status           VARCHAR(20)  NOT NULL,
    rejection_reason VARCHAR(300),
    commission_bp    INT          NOT NULL,
    rating           NUMERIC(2, 1),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT REFERENCES categories (id),
    slug       VARCHAR(80) NOT NULL UNIQUE,
    name_fr    VARCHAR(80) NOT NULL,
    name_ar    VARCHAR(80) NOT NULL,
    name_en    VARCHAR(80) NOT NULL,
    vat_bp     INT         NOT NULL DEFAULT 1900,
    sort_order INT         NOT NULL DEFAULT 0
);

CREATE TABLE brands (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    BIGINT        NOT NULL REFERENCES categories (id),
    brand_id       BIGINT REFERENCES brands (id),
    title          VARCHAR(200)  NOT NULL,
    description    VARCHAR(4000) NOT NULL,
    ean            VARCHAR(14) UNIQUE,
    image_url      VARCHAR(500),
    vat_bp         INT           NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    rejection_reason VARCHAR(300),
    created_by_seller_id BIGINT REFERENCES sellers (id),
    best_price     BIGINT,
    in_stock       BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_status ON products (status);

CREATE TABLE offers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT  NOT NULL REFERENCES products (id),
    seller_id        BIGINT  NOT NULL REFERENCES sellers (id),
    price            BIGINT  NOT NULL,
    compare_at_price BIGINT,
    stock            INT     NOT NULL,
    max_per_order    INT     NOT NULL DEFAULT 10,
    handling_days    INT     NOT NULL DEFAULT 1,
    item_condition   VARCHAR(20) NOT NULL DEFAULT 'NEW',
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    version          BIGINT  NOT NULL DEFAULT 0,
    CONSTRAINT uq_offer_product_seller UNIQUE (product_id, seller_id)
);

CREATE TABLE cart_items (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL REFERENCES users (id),
    offer_id BIGINT NOT NULL REFERENCES offers (id),
    quantity INT    NOT NULL,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_cart_user_offer UNIQUE (user_id, offer_id)
);

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number         VARCHAR(20)  NOT NULL UNIQUE,
    user_id        BIGINT       NOT NULL REFERENCES users (id),
    status         VARCHAR(30)  NOT NULL,
    payment_method VARCHAR(20)  NOT NULL,
    items_total    BIGINT       NOT NULL,
    shipping_total BIGINT       NOT NULL,
    stamp_duty     BIGINT       NOT NULL,
    cod_fee        BIGINT       NOT NULL,
    total          BIGINT       NOT NULL,
    ship_full_name   VARCHAR(120) NOT NULL,
    ship_phone       VARCHAR(20)  NOT NULL,
    ship_governorate VARCHAR(80)  NOT NULL,
    ship_delegation  VARCHAR(80)  NOT NULL,
    ship_locality    VARCHAR(80),
    ship_postal_code VARCHAR(4)   NOT NULL,
    ship_street      VARCHAR(200) NOT NULL,
    ship_landmark    VARCHAR(200),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_orders_user ON orders (user_id);

CREATE TABLE sub_orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT      NOT NULL REFERENCES orders (id),
    seller_id       BIGINT      NOT NULL REFERENCES sellers (id),
    status          VARCHAR(30) NOT NULL,
    items_total     BIGINT      NOT NULL,
    shipping_fee    BIGINT      NOT NULL,
    commission      BIGINT      NOT NULL,
    tracking_number VARCHAR(40),
    cancel_reason   VARCHAR(300),
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sub_orders_seller ON sub_orders (seller_id, status);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sub_order_id BIGINT       NOT NULL REFERENCES sub_orders (id),
    offer_id     BIGINT       NOT NULL REFERENCES offers (id),
    product_id   BIGINT       NOT NULL REFERENCES products (id),
    title        VARCHAR(200) NOT NULL,
    unit_price   BIGINT       NOT NULL,
    quantity     INT          NOT NULL,
    vat_bp       INT          NOT NULL,
    line_total   BIGINT       NOT NULL
);

CREATE TABLE order_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL REFERENCES orders (id),
    sub_order_id BIGINT REFERENCES sub_orders (id),
    status       VARCHAR(30) NOT NULL,
    note         VARCHAR(300),
    actor        VARCHAR(20) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_order_events_order ON order_events (order_id);
